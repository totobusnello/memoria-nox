#!/usr/bin/env python3
"""Step 2 readings (PREREGISTRATION.md §4 to §6, §8), from the primary runs.

    python3 -I analyze.py            # writes results/stage2.txt and results/stage2.json
    python3 -I analyze.py --check    # fails if the committed results differ from a fresh analysis
    python3 -I analyze.py --fixtures # §5 only: the citation check on offline fixtures

Every rate is printed as numerator/denominator; denominator zero prints as undefined.
"""
import collections
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent))
import judges as J  # noqa: E402
import run as RUN  # noqa: E402
import metrics as M  # noqa: E402  (step 1's nDCG, synthetic-ptbr/metrics.py)

OUT_TXT = HERE / "results" / "stage2.txt"
OUT_JSON = HERE / "results" / "stage2.json"
HUMAN_ANSWERS = {"default": {"C"}, "gold": {"C", "P"}}


def rate(n, d):
    return {"n": n, "d": d, "value": round(n / d, 4) if d else None}


def fmt(r):
    return f"{r['n']}/{r['d']} = {r['value']}" if r["d"] else f"{r['n']}/0 = undefined"


def kappa(a, b):
    """Cohen's kappa on two aligned lists of booleans; None when undefined."""
    n = len(a)
    if n == 0:
        return None
    po = sum(x == y for x, y in zip(a, b)) / n
    pa, pb = sum(a) / n, sum(b) / n
    pe = pa * pb + (1 - pa) * (1 - pb)
    return None if pe == 1 else round((po - pe) / (1 - pe), 4)


def confusion(pred, truth):
    tp = sum(p and t for p, t in zip(pred, truth))
    fp = sum(p and not t for p, t in zip(pred, truth))
    fn = sum(t and not p for p, t in zip(pred, truth))
    tn = sum(not p and not t for p, t in zip(pred, truth))
    return {"tp": tp, "fp": fp, "fn": fn, "tn": tn, "precision": rate(tp, tp + fp),
            "recall": rate(tp, tp + fn), "kappa": kappa(pred, truth)}


def labels(instrument, field="label"):
    rows = RUN.primary(instrument) or []
    return {r["key"]: r["parsed"][field] for r in rows if r["parsed"].get("valid")}, len(rows)


def fixtures():
    fx = json.loads((HERE / "citation-fixtures.json").read_text())
    lines = ["## 5. The citation check on offline fixtures (no model)", ""]
    out = []
    for f in fx:
        r = {"case": f["case"], "oracle_160": J.oracle_quote_ok(f["quote"], f["chunk"]),
             "whole_quote": J.whole_quote_ok(f["quote"], f["chunk"]),
             "eight_words": J.eight_words_ok(f["quote"], f["chunk"])}
        out.append(r)
        lines.append(f"- {f['case']}: oracle-160 {'pass' if r['oracle_160'] else 'veto'}, "
                     f"whole {'pass' if r['whole_quote'] else 'veto'}, "
                     f"8-word {'pass' if r['eight_words'] else 'veto'}")
    return out, lines


def analyze():
    data, qtext, text = RUN.load()
    pairs = data["pairs"]
    key = lambda p: f"{p['query']}:{p['chunk']}"  # noqa: E731
    keys = [key(p) for p in pairs]
    T = {key(p): p["T"] for p in pairs}
    top = {key(p) for p in pairs if p["source"].startswith("top")}
    rep, L = {}, ["# Synthetic PT-BR corpus, step 2: Paper A's judges against the planted key",
                  "# (generated by stage2/analyze.py)", ""]

    lab, n_run = {}, {}
    for i in ("oracle", "pool", "reg", "reg2", "envelope", "gold"):
        lab[i], n_run[i] = labels(i)
    pool_leg, _ = labels("pool", "label_with_leg")
    lab["pool_leg"] = pool_leg
    oracle_rows = {r["key"]: r["parsed"] for r in (RUN.primary("oracle") or []) if r["parsed"].get("valid")}

    # missing per instrument
    L.append("## Missing labels")
    rep["missing"] = {}
    for i, n in n_run.items():
        m = n - len(lab[i])
        rep["missing"][i] = {"missing": m, "units": n}
        L.append(f"- {i}: {m} of {n}")
    L.append("")

    # 6. each instrument against T, on all pairs and on the top-10
    L.append("## 6. Each instrument against T (primary)")
    rep["against_T"] = {}
    for i in ("oracle", "pool", "pool_leg", "reg", "reg2", "envelope", "gold"):
        for scope, ks in (("all", keys), ("top10", [k for k in keys if k in top])):
            ks = [k for k in ks if k in lab[i]]
            c = confusion([lab[i][k] for k in ks], [T[k] for k in ks])
            rep["against_T"][f"{i}/{scope}"] = c
            L.append(f"- {i} ({scope}, n={len(ks)}): tp {c['tp']} fp {c['fp']} fn {c['fn']} tn {c['tn']}; "
                     f"precision {fmt(c['precision'])}; recall {fmt(c['recall'])}; kappa {c['kappa']}")
    L.append("- kappa between judges (pairs where both are valid), beside each one's kappa against T:")
    rep["between"] = {}
    names = ["oracle", "pool", "reg", "gold"]
    for a_i, a in enumerate(names):
        for b in names[a_i + 1:]:
            ks = [k for k in keys if k in lab[a] and k in lab[b]]
            kb = kappa([lab[a][k] for k in ks], [lab[b][k] for k in ks])
            rep["between"][f"{a}~{b}"] = {"n": len(ks), "kappa": kb}
            L.append(f"  - {a} ~ {b}: {kb} (n={len(ks)}); against T {rep['against_T'][a + '/all']['kappa']} "
                     f"and {rep['against_T'][b + '/all']['kappa']}")
    L.append("")

    # 1. quotation
    L.append("## 1. Quotation (J-oracle, J-repass), this corpus only")
    pos = {k: v for k, v in oracle_rows.items() if v["label"]}
    empty = sum(1 for v in pos.values() if not v["quote"])
    fail160 = [k for k, v in pos.items() if not v["quote_ok"]]
    whole_only = sum(1 for v in pos.values() if v["quote_ok"] and not v["whole_quote_ok"])
    repass, _ = labels("repass", "citacao_confere")
    verified = sum(1 for k in fail160 if repass.get(k))
    rep["quotation"] = {"positives": len(pos), "empty": rate(empty, len(pos)),
                        "fail_160": rate(len(fail160), len(pos)),
                        "pass_160_fail_whole": rate(whole_only, len(pos)),
                        "repass_verified": rate(verified, len(fail160)),
                        "repass_missing": len(fail160) - sum(1 for k in fail160 if k in repass)}
    q = rep["quotation"]
    L += [f"- J-oracle positives: {len(pos)}",
          f"- empty quote: {fmt(q['empty'])}", f"- fail the 160-character check: {fmt(q['fail_160'])}",
          f"- pass 160 but fail the whole quote: {fmt(q['pass_160_fail_whole'])}",
          f"- of the 160 failures, J-repass verifies: {fmt(q['repass_verified'])} "
          f"(missing {q['repass_missing']})", ""]

    # 2. the citation leg
    L.append("## 2. The citation leg (J-pool)")
    pool_rows = {r["key"]: r["parsed"] for r in (RUN.primary("pool") or []) if r["parsed"].get("valid")}
    table = collections.Counter()
    for k, v in pool_rows.items():
        if v["label"]:
            reg = lab["reg"].get(k)
            table[(("leg_pass" if v["citacao_confere"] else "leg_fail"), ("T" if T[k] else "notT"),
                   ("reg_yes" if reg else "reg_no" if reg is not None else "reg_missing"))] += 1
    rep["citation_leg"] = {"table": {"/".join(k): n for k, n in sorted(table.items())}}
    for k, n in sorted(table.items()):
        L.append(f"- {' · '.join(k)}: {n}")
    both = [k for k in keys if k in lab["pool"] and k in lab["reg"]]
    k_without = kappa([lab["pool"][k] for k in both], [lab["reg"][k] for k in both])
    k_with = kappa([lab["pool_leg"][k] for k in both], [lab["reg"][k] for k in both])
    rep["citation_leg"].update({"n": len(both), "kappa_with_reg_without_leg": k_without,
                                "kappa_with_reg_with_leg": k_with,
                                "against_T_without": rep["against_T"]["pool/all"],
                                "against_T_with": rep["against_T"]["pool_leg/all"]})
    L += [f"- kappa with J-reg (n={len(both)}): without the leg {k_without}, with the leg {k_with}",
          f"- against T: precision {fmt(rep['against_T']['pool/all']['precision'])} -> "
          f"{fmt(rep['against_T']['pool_leg/all']['precision'])}; recall "
          f"{fmt(rep['against_T']['pool/all']['recall'])} -> {fmt(rep['against_T']['pool_leg/all']['recall'])}", ""]

    # 3. negatives
    L.append("## 3. Negatives")
    rep["negatives"] = {"false_premise": {}, "context_negative": {}}
    for p in pairs:
        k = key(p)
        if p["kind"] == "false_premise" or p["context_negative"]:
            said = [i for i in ("oracle", "pool", "reg", "envelope", "gold") if lab[i].get(k)]
            bucket = "false_premise" if p["kind"] == "false_premise" else "context_negative"
            if bucket == "false_premise":
                rep["negatives"][bucket].setdefault(p["query"], {i: 0 for i in ("oracle", "pool", "reg", "envelope", "gold")})
                for i in said:
                    rep["negatives"][bucket][p["query"]][i] += 1
            else:
                rep["negatives"][bucket][k] = said
    for qid, c in sorted(rep["negatives"]["false_premise"].items()):
        L.append(f"- false premise {qid}: pairs labelled as answering " + ", ".join(f"{i} {n}" for i, n in c.items()))
    for k, said in sorted(rep["negatives"]["context_negative"].items()):
        L.append(f"- context negative {k}: {', '.join(said) or 'none'}")
    prem = {r["key"]: r["parsed"] for r in (RUN.primary("premise") or []) if r["parsed"].get("valid")}
    fp_keys = {key(pairs[i]) for i in data["premise_pairs"] if pairs[i]["kind"] == "false_premise"}
    tpos_keys = {key(pairs[i]) for i in data["premise_pairs"] if pairs[i]["kind"] == "fact" and pairs[i]["T"]}
    rep["premise"] = {
        "false_premise_supports": rate(sum(1 for k in fp_keys if prem.get(k, {}).get("relacao") == "sustenta"),
                                       sum(1 for k in fp_keys if k in prem)),
        "fact_T_supports": rate(sum(1 for k in tpos_keys if prem.get(k, {}).get("relacao") == "sustenta"),
                                sum(1 for k in tpos_keys if k in prem))}
    L += [f"- J-premise (exploratory): false-premise pairs said to support the premise "
          f"{fmt(rep['premise']['false_premise_supports'])}; fact pairs true in T said to support it "
          f"{fmt(rep['premise']['fact_T_supports'])}", ""]

    # 4. gold check
    L.append("## 4. Gold check (J-gold)")
    rep["gold_check"] = {}
    for grp in ("correct", "wrong_superseded_or_rejected", "random"):
        ks = [f"{g['query']}:{g['chunk']}" for g in data["gold_check"] if g["as_gold"] == grp]
        acc = sum(1 for k in ks if lab["gold"].get(k))
        rep["gold_check"][grp] = rate(acc, sum(1 for k in ks if k in lab["gold"]))
        L.append(f"- accepted, {grp}: {fmt(rep['gold_check'][grp])}")
    by_q = collections.defaultdict(list)
    for g in data["gold_check"]:
        if g["as_gold"] == "correct":
            by_q[g["query"]].append(lab["gold"].get(f"{g['query']}:{g['chunk']}"))
    all_rej = sorted(q for q, v in by_q.items() if v and all(x is False for x in v))
    rep["gold_check"]["queries_all_R_rejected"] = all_rej
    L += [f"- fact queries whose whole R J-gold rejects: {len(all_rej)} {all_rej}", ""]

    # 5. stability
    L.append("## 5. Stability")
    rep["stability"] = {}
    probs = {i: {r["key"]: r["parsed"]["p"] for r in (RUN.primary(i) or []) if r["parsed"].get("valid")}
             for i in ("reg", "reg2", "envelope")}
    for other in ("reg2", "envelope"):
        ks = [k for k in keys if k in probs["reg"] and k in probs[other]]
        flips = [k for k in ks if (probs["reg"][k] > J.THRESHOLD) != (probs[other][k] > J.THRESHOLD)]
        up = sum(1 for k in flips if probs[other][k] > J.THRESHOLD)
        bands = collections.Counter()
        for k in ks:
            d = abs(probs["reg"][k] - probs[other][k])
            bands["crossing" if k in flips else "0-0.1" if d <= 0.1 else "0.1-0.3" if d <= 0.3 else "over 0.3"] += 1
        rep["stability"][other] = {"n": len(ks), "flips": len(flips), "to_positive": up,
                                   "to_negative": len(flips) - up, "bands": dict(bands)}
        L.append(f"- J-reg vs {other} (n={len(ks)}): {len(flips)} labels changed "
                 f"({up} to positive, {len(flips) - up} to negative); |dp| bands {dict(sorted(bands.items()))}")
    plan = json.loads((HERE.parent / "plan" / "plan.json").read_text())
    rankings = json.loads((HERE.parent / "results" / "3.11.1" / "rankings.json").read_text())
    ndcg = collections.defaultdict(list)
    complete, apart = [], []
    for qd in plan["queries"]:
        if qd["kind"] != "fact":
            apart.append(qd["id"])
            continue
        rank = [x["id"] for x in rankings[qd["id"]]][:10]
        ks = [f"{qd['id']}:{c}" for c in rank]
        if not all(k in probs[i] for k in ks for i in ("reg", "reg2", "envelope")):
            apart.append(qd["id"])
            continue
        complete.append(qd["id"])
        Rset = {p["chunk"] for p in pairs if p["query"] == qd["id"] and p["R"]}
        Tset = {p["chunk"] for p in pairs if p["query"] == qd["id"] and p["T"]}
        for i in ("reg", "reg2", "envelope"):
            pooled = Rset | {c for c in rank if probs[i][f"{qd['id']}:{c}"] > J.THRESHOLD}
            ndcg[i].append(M.ndcg_gold(rank, pooled))
        ndcg["T"].append(M.ndcg_gold(rank, Tset))
    rep["stability"]["ndcg_pooled"] = {i: (round(sum(v) / len(v), 4) if v else None) for i, v in ndcg.items()}
    rep["stability"]["ndcg_queries"] = {"complete": len(complete), "apart": apart}
    L += [f"- pooled nDCG@10 over {len(complete)} complete fact queries: "
          + ", ".join(f"{i} {v}" for i, v in rep["stability"]["ndcg_pooled"].items()),
          f"- listed apart: {apart}", ""]

    # 7. human sample
    L.append("## 7. Against the human sample (secondary)")
    ann = {}
    for line in RUN.ANNOT.read_text().splitlines()[1:]:
        if line.strip():
            parts = line.split("\t")
            ann[int(parts[0])] = (parts[1].strip(), parts[2].strip() if len(parts) > 2 else "")
    sample = data["human_sample"]
    strata = collections.defaultdict(list)
    for s in sample:
        code, note = ann[s["row"]]
        strata[s["stratum"]].append((s, code, note))
    rep["human"] = {"undecided": sum(1 for s in sample if ann[s["row"]][0] == "?")}
    dis_rows = []
    weighted_dis = weighted_tot = 0.0
    for st, rows in strata.items():
        dec = [(s, c, n) for s, c, n in rows if c != "?"]
        dis = [(s, c, n) for s, c, n in dec if (c in HUMAN_ANSWERS["default"]) != pairs[s["pair"]]["T"]]
        rep["human"][st] = rate(len(dis), len(dec))
        for s, c, n in dec:
            w = 1 / s["inclusion"]
            weighted_tot += w
            weighted_dis += w * ((c in HUMAN_ANSWERS["default"]) != pairs[s["pair"]]["T"])
        dis_rows += [{"row": s["row"], "pair": key(pairs[s["pair"]]), "stratum": st, "code": c,
                      "T": pairs[s["pair"]]["T"], "note": n} for s, c, n in dis]
        L.append(f"- T disagrees with the human reading, {st}: {fmt(rep['human'][st])}")
    rep["human"]["weighted_disagreement"] = round(weighted_dis / weighted_tot, 4) if weighted_tot else None
    rep["human"]["disagreeing_rows"] = dis_rows
    L.append(f"- weighted estimate over the 555: {rep['human']['weighted_disagreement']}; undecided rows "
             f"{rep['human']['undecided']}")
    for r in dis_rows:
        L.append(f"  - row {r['row']} {r['pair']} ({r['stratum']}): human {r['code']}, T {r['T']} {r['note']}")
    rep["human"]["instruments"] = {}
    for i in ("oracle", "pool", "pool_leg", "reg", "envelope", "gold"):
        ans = HUMAN_ANSWERS["gold" if i == "gold" else "default"]
        pred, truth, w = [], [], []
        for s in sample:
            k = key(pairs[s["pair"]])
            code = ann[s["row"]][0]
            if code == "?" or k not in lab[i]:
                continue
            pred.append(lab[i][k]); truth.append(code in ans); w.append(1 / s["inclusion"])
        c = confusion(pred, truth)
        wtp = sum(wi for p_, t_, wi in zip(pred, truth, w) if p_ and t_)
        wfp = sum(wi for p_, t_, wi in zip(pred, truth, w) if p_ and not t_)
        wfn = sum(wi for p_, t_, wi in zip(pred, truth, w) if t_ and not p_)
        c["weighted_precision"] = round(wtp / (wtp + wfp), 4) if wtp + wfp else None
        c["weighted_recall"] = round(wtp / (wtp + wfn), 4) if wtp + wfn else None
        rep["human"]["instruments"][i] = c
        L.append(f"- {i} against the human reading (n={len(pred)}): precision {fmt(c['precision'])} "
                 f"(weighted {c['weighted_precision']}), recall {fmt(c['recall'])} "
                 f"(weighted {c['weighted_recall']}), kappa {c['kappa']}")
    L.append("")

    # 8. predictions
    L.append("## 8. Predictions carried over from Paper A")
    st = rep["stability"]
    kp = rep["citation_leg"]
    preds = {
        "P1": (q["fail_160"]["n"] >= 1, f"{fmt(q['fail_160'])} J-oracle positives fail the 160 check"),
        "P2": (None if kp["kappa_with_reg_with_leg"] is None or kp["kappa_with_reg_without_leg"] is None
               else kp["kappa_with_reg_with_leg"] < kp["kappa_with_reg_without_leg"],
               f"kappa with J-reg {kp['kappa_with_reg_without_leg']} -> {kp['kappa_with_reg_with_leg']}"),
        "P3": (st["reg2"]["flips"] == 0, f"{st['reg2']['flips']} of {st['reg2']['n']} labels changed"),
        "P4": (st["envelope"]["flips"] >= 1, f"{st['envelope']['flips']} of {st['envelope']['n']} labels changed"),
        "P5": (rep["gold_check"]["random"]["n"] <= 2,
               f"random accepted {fmt(rep['gold_check']['random'])}; correct gold accepted "
               f"{fmt(rep['gold_check']['correct'])}"),
    }
    rep["predictions"] = {}
    for p_, (seen, why) in preds.items():
        word = "undefined" if seen is None else "seen again" if seen else "not seen again"
        rep["predictions"][p_] = {"result": word, "counts": why}
        L.append(f"- {p_}: {word} ({why})")
    L.append("")

    fx, fl = fixtures()
    rep["fixtures"] = fx
    L += fl
    return rep, "\n".join(L) + "\n"


def main():
    if "--fixtures" in sys.argv:
        print("\n".join(fixtures()[1]))
        return
    rep, txt = analyze()
    js = json.dumps(rep, ensure_ascii=False, indent=1) + "\n"
    if "--check" in sys.argv:
        if OUT_TXT.read_text() != txt or OUT_JSON.read_text() != js:
            sys.exit("stage2 results drifted from analyze.py")
        print("stage2 analyze --check: ok")
        return
    OUT_TXT.parent.mkdir(exist_ok=True)
    OUT_TXT.write_text(txt)
    OUT_JSON.write_text(js)
    print(txt)


if __name__ == "__main__":
    main()
