#!/usr/bin/env python3
"""Step 2 supplement (2026-11-26): readings the pre-registration promised and the frozen
`analyze.py` did not print, plus two post-hoc checks the review asked for. Same stored labels,
no model call. The frozen output (`results/stage2.txt`) is left as it is.

    python3 -I supplement.py           # writes results/stage2-supplement.txt
    python3 -I supplement.py --check   # fails if the committed file differs

Registered and missing from the frozen output (PREREGISTRATION.md §3, §4.6, §4.7, §7, §4.3):
  R1  J-oracle under the source's full rule against T
  R2  each instrument against the human reading, per stratum
  R3  missing labels per instrument and stratum
  R4  J-premise on the 25 fact pairs false in T
  R5  kappa between judges on the 500 top-10 pairs
Post-hoc, asked for by the reviewers of the note, marked as such:
  H1  kappa against T on the pairs valid for both judges of each pair
  H2  per question, pooled nDCG@10 with J-reg against pooling with a perfect judge
  H3  false acceptances on the 15 context negatives as a share of each judge's false positives,
      and the shared acceptances of J-pool and J-gold
"""
import collections
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent))
import analyze as A  # noqa: E402
import judges as J  # noqa: E402
import metrics as M  # noqa: E402
import run as RUN  # noqa: E402

OUT = HERE / "results" / "stage2-supplement.txt"
JUDGES = ("oracle", "pool", "pool_leg", "reg", "envelope", "gold")


def build():
    data, qtext, text = RUN.load()
    pairs = data["pairs"]
    key = lambda p: f"{p['query']}:{p['chunk']}"  # noqa: E731
    keys = [key(p) for p in pairs]
    T = {key(p): p["T"] for p in pairs}
    pmeta = {key(p): p for p in pairs}
    lab = {i: A.labels(i)[0] for i in ("oracle", "pool", "reg", "envelope", "gold")}
    lab["pool_leg"] = A.labels("pool", "label_with_leg")[0]
    L = ["# Synthetic PT-BR corpus, step 2 supplement (generated by stage2/supplement.py, 2026-11-26)",
         "# Same stored labels as results/stage2.txt; no model call.", ""]

    # R1
    full = A.labels("oracle", "label_source_rule")[0]
    ks = [k for k in keys if k in full]
    c = A.confusion([full[k] for k in ks], [T[k] for k in ks])
    L += ["## R1. J-oracle under the source's full rule (registered, PREREGISTRATION.md §3)",
          f"- rule: trecho_responde AND NOT sem_fonte_ja_responde AND quote check (n={len(ks)})",
          f"- tp {c['tp']} fp {c['fp']} fn {c['fn']} tn {c['tn']}; precision {A.fmt(c['precision'])}; "
          f"recall {A.fmt(c['recall'])}; kappa {c['kappa']}", ""]

    # R2
    ann = {}
    for line in RUN.ANNOT.read_text().splitlines()[1:]:
        if line.strip():
            parts = line.split("\t")
            ann[int(parts[0])] = parts[1].strip()
    L.append("## R2. Each instrument against the human reading, per stratum (registered, §4.7)")
    for i in JUDGES:
        ans = A.HUMAN_ANSWERS["gold" if i == "gold" else "default"]
        by = collections.defaultdict(lambda: [[], []])
        for s in data["human_sample"]:
            k = key(pairs[s["pair"]])
            if ann[s["row"]] == "?" or k not in lab[i]:
                continue
            by[s["stratum"]][0].append(lab[i][k])
            by[s["stratum"]][1].append(ann[s["row"]] in ans)
        cells = []
        for st in ("truth", "context_negative", "false_premise", "other_false"):
            pr, tr = by[st]
            c = A.confusion(pr, tr)
            cells.append(f"{st} n={len(pr)} tp {c['tp']} fp {c['fp']} fn {c['fn']} tn {c['tn']}")
        L.append(f"- {i}: " + "; ".join(cells))
    L.append("")

    # R3
    L.append("## R3. Missing labels per instrument and stratum (registered, §7)")
    for i in ("oracle", "pool", "reg", "envelope", "gold"):
        miss = [k for k in keys if k not in lab[i]]
        where = collections.Counter(
            "context_negative" if pmeta[k]["context_negative"] else
            "false_premise" if pmeta[k]["kind"] == "false_premise" else
            "truth" if pmeta[k]["T"] else pmeta[k]["source"].rstrip("0123456789") for k in miss)
        L.append(f"- {i}: {len(miss)} missing {dict(sorted(where.items()))} {miss}")
    L.append("")

    # R4
    prem = {r["key"]: r["parsed"] for r in (RUN.primary("premise") or []) if r["parsed"].get("valid")}
    neg = [key(pairs[i]) for i in data["premise_pairs"] if pairs[i]["kind"] == "fact" and not pairs[i]["T"]]
    dist = collections.Counter(prem[k]["relacao"] if k in prem else "missing" for k in neg)
    L += ["## R4. J-premise on the 25 fact pairs false in T (registered as reported without a reading, §4.3)",
          f"- {dict(sorted(dist.items()))}", ""]

    # R5
    L.append("## R5. Kappa between judges on the 500 top-10 pairs (registered, §4)")
    names = ["oracle", "pool", "reg", "gold"]
    top = [k for k in keys if pmeta[k]["source"].startswith("top")]
    for a_i, a in enumerate(names):
        for b in names[a_i + 1:]:
            ks = [k for k in top if k in lab[a] and k in lab[b]]
            L.append(f"- {a} ~ {b}: {A.kappa([lab[a][k] for k in ks], [lab[b][k] for k in ks])} (n={len(ks)})")
    L.append("")

    # H1
    L.append("## H1. Post-hoc: kappa against T on the pairs valid for both judges of each pair")
    for a_i, a in enumerate(names):
        for b in names[a_i + 1:]:
            ks = [k for k in keys if k in lab[a] and k in lab[b]]
            ka = A.kappa([lab[a][k] for k in ks], [T[k] for k in ks])
            kb = A.kappa([lab[b][k] for k in ks], [T[k] for k in ks])
            kab = A.kappa([lab[a][k] for k in ks], [lab[b][k] for k in ks])
            L.append(f"- {a} ~ {b}: {kab}; {a} ~ T {ka}; {b} ~ T {kb} (n={len(ks)})")
    L.append("")

    # H2
    plan = json.loads((HERE.parent / "plan" / "plan.json").read_text())
    rankings = json.loads((HERE.parent / "results" / "3.11.1" / "rankings.json").read_text())
    probs = {r["key"]: r["parsed"]["p"] for r in (RUN.primary("reg") or []) if r["parsed"].get("valid")}
    moves = collections.Counter()
    detail = []
    for q in plan["queries"]:
        if q["kind"] != "fact":
            continue
        rank = [x["id"] for x in rankings[q["id"]]][:10]
        R = {p["chunk"] for p in pairs if p["query"] == q["id"] and p["R"]}
        Tset = {p["chunk"] for p in pairs if p["query"] == q["id"] and p["T"]}
        perfect = M.ndcg_gold(rank, M.pooled(R, Tset, rank))
        judged = M.ndcg_gold(rank, R | {c for c in rank if probs[f"{q['id']}:{c}"] > J.THRESHOLD})
        d = "up" if judged > perfect + 1e-12 else "down" if judged < perfect - 1e-12 else "equal"
        moves[d] += 1
        if d != "equal":
            detail.append(f"{q['id']} {round(perfect, 4)} -> {round(judged, 4)}")
    L += ["## H2. Post-hoc: per question, pooled nDCG@10 with J-reg against pooling with a perfect judge",
          f"- 45 fact questions: up {moves['up']}, down {moves['down']}, equal {moves['equal']}",
          "- " + "; ".join(detail), ""]

    # H3
    L.append("## H3. Post-hoc: context negatives among each judge's false positives (all 555 pairs)")
    tot_fp = tot_ctx = 0
    for i in ("oracle", "pool", "reg", "envelope", "gold"):
        fp = [k for k in keys if lab[i].get(k) and not T[k]]
        ctx = [k for k in fp if pmeta[k]["context_negative"]]
        rnd = [k for k in fp if pmeta[k]["source"] == "random"]
        tot_fp += len(fp)
        tot_ctx += len(ctx)
        L.append(f"- {i}: {len(ctx)} of {len(fp)} false positives are context negatives; "
                 f"random pairs accepted {len(rnd)}")
    L.append(f"- five judges together (J-reg-2 not counted): {tot_ctx} of {tot_fp}")
    shared = [k for k in keys if pmeta[k]["context_negative"] and lab["gold"].get(k) and lab["pool"].get(k)]
    L += [f"- context negatives accepted by both J-pool and J-gold: {len(shared)} "
          f"(J-gold accepted {sum(1 for k in keys if pmeta[k]['context_negative'] and lab['gold'].get(k))})", ""]
    return "\n".join(L) + "\n"


def main():
    txt = build()
    if "--check" in sys.argv:
        if OUT.read_text() != txt:
            sys.exit("stage2 supplement drifted from supplement.py")
        print("stage2 supplement --check: ok")
        return
    OUT.write_text(txt)
    print(txt)


if __name__ == "__main__":
    main()
