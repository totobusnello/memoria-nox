def leaves(o):
    if isinstance(o, dict):
        for v in o.values():
            yield from leaves(v)
    elif isinstance(o, list):
        for v in o:
            yield from leaves(v)
    elif isinstance(o, (int, float)) and not isinstance(o, bool):
        yield float(o)


def forms(v):
    out = set()
    for x in (abs(v), abs(v) * 100):
        for d in range(0, 6):
            t = f"{x:.{d}f}"
            out.add(t)
            if "." in t:
                out.add(t.rstrip("0").rstrip(".") if d else t)
        if float(x).is_integer():
            out.add(str(int(x)))
    return out


