def check(old, new, verbose=True, report=False, integ=None):
    fails = []
    reg = json.loads(ART["ITT-REGISTRADO-v3"].read_text())
    chk = json.loads(ART["checks-rc10"].read_text())
    f4 = json.loads(ART["f4-w4"].read_text())
    f3 = json.loads(ART["f3-abort"].read_text())
    itt = json.loads(ART["ITT-2026-09-21"].read_text())
    allowed_art = artifact_numbers()
    der = derived(reg, chk, itt)
    old_nums = numbers(old)
    hs = hunks(old, new)
    # 1 hunks
    for h in hs:
        if not h["ids"]:
            fails.append(f"hunk rc10 {h['rc10']} rc11 {h['rc11']} has no ID: {h['new'][:70]!r}")
    # 2 numbers per hunk
    rep = collections.defaultdict(lambda: dict(added=[], removed=[]))
    for h in hs:
        add = numbers(h["new"]) - numbers(h["old"])
        rem = numbers(h["old"]) - numbers(h["new"])
        key = "+".join(h["ids"]) or "?"
        for tok, n in sorted(add.items()):
            why = None
            if tok in old_nums:
                why = "rc10"
            elif tok in allowed_art:
                why = "artifact:" + allowed_art[tok]
            elif tok in der:
                why = "derived: " + der[tok]
            else:
                for i in h["ids"]:
                    if tok in LITERALS.get(i, {}):
                        why = f"literal[{i}]: " + LITERALS[i][tok]
                        break
            rep[key]["added"].append((tok, n, why))
            if why is None:
                fails.append(f"number '{tok}' (+{n}) added in hunk {key} (rc11 l.{h['rc11'][0]}) is not justified")
        for tok, n in sorted(rem.items()):
            rep[key]["removed"].append((tok, n))
    # 3 headline values
    flat = " ".join(new.split())
    for k, v in headline(reg, chk, f4, f3, itt).items():
        if " ".join(v.split()) not in flat:
            fails.append(f"headline: {k} — expected text {v!r} (from the artifact) not found in rc11")
    # the census deviation is declared twice: in §4 and in Appendix A (Codex 1 asks for both)
    dev = " ".join(headline(reg, chk, f4, f3, itt)["census deviation"].split())
    sec4 = " ".join(new[new.find("\n## 4. Results"):new.find("\n### 4.0.1 ")].split())
    appa = " ".join(new[new.find("\n## Appendix A"):new.find("\n## Appendix B")].split())
    for nome, parte in (("§4", sec4), ("Appendix A", appa)):
        if dev not in parte:
            fails.append(f"census: the deviation is not declared in {nome}")
    # 4 claims
    fails += claims(new)
    # 5 headings
    h8, h9 = headings(old), headings(new)
    expected = [HEADINGS.get(h, (h, None))[0] for h in h8]
    if expected != h9:
        for x, y in zip(expected + [None] * 9, h9 + [None] * 9):
            if x != y:
                fails.append(f"heading: expected {x!r}, found {y!r}")
                break
    # 6 citations and footnotes
    for name, t in (("rc10", old), ("rc11", new)):
        body, refs = body_and_refs(t)
        used = set(re.findall(r"@([A-Za-z0-9_]+)", " ".join(CITE.findall(body))))
        listed = set(re.findall(r"`\[@([A-Za-z0-9_]+)\]`", refs))
        if used - listed:
            fails.append(f"citation ({name}): used but not listed: {sorted(used - listed)}")
        fm = set(re.findall(r"\[\^([^\]]+)\](?!:)", t))
        fd = set(re.findall(r"^\[\^([^\]]+)\]:", t, re.M))
        if fm - fd:
            fails.append(f"footnote ({name}): markers without definition {sorted(fm - fd)}")
    cn = collections.Counter(re.findall(r"@([A-Za-z0-9_]+)", " ".join(CITE.findall(body_and_refs(new)[0]))))
    co = collections.Counter(re.findall(r"@([A-Za-z0-9_]+)", " ".join(CITE.findall(body_and_refs(old)[0]))))
    if cn != co:
        fails.append(f"citation: occurrences changed: +{dict(cn - co)} -{dict(co - cn)}")
    if collections.Counter(DOI.findall(old)) != collections.Counter(DOI.findall(new)):
        fails.append("doi: DOI multiset changed")
    # 7 forbidden additions
    for pat in FORBIDDEN:
        if len(re.findall(pat, new)) > len(re.findall(pat, old)):
            fails.append(f"forbidden: pattern {pat!r} added")
    # 8 SHAM-JANELA
    so, eo = sham_spans(old)
    sn, en = sham_spans(new)
    fails += eo + en
    if len(sn) != EXPECTED_SHAM or len(so) != EXPECTED_SHAM:
        fails.append(f"sham: {len(sn)} blocks in rc11 and {len(so)} in rc10, expected {EXPECTED_SHAM}")
    for i, (x, y) in enumerate(zip(so, sn), 1):
        if x != y:
            fails.append(f"sham: block {i} ({y.strip()[:50]!r}…) is not byte-identical to rc10")
    # 9 no REANALISE comment marker
    if R_ANY.search(new):
        fails.append("reanalise: a REANALISE marker is present in rc11")
    # 10 quotes
    def nq(x):
        return " ".join(x.replace("**", "").split())
    fontes = nq(old) + " " + " ".join(nq(p.read_text()) for p in QUOTE_SOURCES)
    qo, qn = collections.Counter(QUOTE.findall(old)), collections.Counter(QUOTE.findall(new))
    for q in (qn - qo):
        if nq(q[2:-2]) not in fontes:
            fails.append(f"quote: {q[:70]!r} is not verbatim in rc10 or a declared source")
    for q in (qo - qn):
        fails.append(f"quote removed: {q[:70]!r}")
    # 11 code spans
    cos, cns = collections.Counter(CODE.findall(old)), collections.Counter(CODE.findall(new))
    roots = [P2, SPRINT, P2 / "out", REPO, LASTRO, SPRINT / "B-rc10", HERE, P2 / "measurement",
             SPRINT / "figures", REG]
    idsrc = "".join(p.read_text() for p in (ART["ITT-REGISTRADO-v3"], ART["checks-rc10"], ART["ITT-2026-09-21"],
                                            SCRIPT, P2 / "pilot_replay.py", P2 / "PREREG-DRAFT.md"))
    for span in (cns - cos):
        s = span.strip()
        if re.search(r"\.(?:py|json|md|svg|png|ndjson|jsonl|sh|tgz|txt|ts)\b|/$|\.\*$|\{", s) and " " not in s:
            pats = [s]
            m = re.search(r"\{([^}]+)\}", s)
            if m:
                pats = [s[:m.start()] + x + s[m.end():] for x in m.group(1).split(",")]
            for pat in pats:
                pat = pat.replace("…", "*")
                if not any(glob.glob(str(r / pat)) for r in roots):
                    fails.append(f"code span: `{span}` names no file on disk")
        elif re.fullmatch(r"[a-z][a-z0-9]*(?:_[a-z0-9]+)+", s):
            if s not in idsrc:
                fails.append(f"code span: identifier `{span}` occurs in none of the named sources")
    # 12 bold balance
    noncode = re.sub(r"```.*?```", "", new, flags=re.S)
    for k, para in enumerate(re.split(r"\n\s*\n", noncode)):
        if para.count("**") % 2:
            fails.append(f"bold: odd number of ** in paragraph {k}: {para.strip()[:60]!r}")
    # 13 script integrity
    fails += script_integrity(**(integ or load_integrity_inputs()))
    if verbose:
        print(f"hunks: {len(hs)}, all with an ID: {all(h['ids'] for h in hs)}")
        na = sum(len(v['added']) for v in rep.values())
        cls = collections.Counter((t[2] or "UNJUSTIFIED").split(":")[0] for v in rep.values() for t in v["added"])
        print(f"numeric tokens added across hunks: {na}; by class: {dict(cls)}")
        print(f"headings: {len(h9)}; renamed: {sum(1 for x, y in zip(h8, h9) if x != y)} (allowed {len(HEADINGS)})")
        print(f"SHAM-JANELA blocks: {len(sn)}, byte-identical to rc10: {sum(1 for x, y in zip(so, sn) if x == y)}")
        print(f"quotes added: {sum((qn - qo).values())}; code spans added: {sum((cns - cos).values())}")
    if report:
        for key, v in rep.items():
            print(f"\n[{key}]")
            for tok, n, why in v["added"]:
                print(f"  + {tok} x{n}  <- {why}")
            if v["removed"]:
                print("  - " + ", ".join(f"{t} x{n}" for t, n in v["removed"]))
    return fails


